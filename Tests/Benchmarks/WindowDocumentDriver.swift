// Appended only to a private diagnostic copy. Uses real business methods and
// native menu/close actions. Never stores a model, window, source or result.
import CryptoKit

private func documentDigest(_ data: Data) -> String {
  SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
}

// Scalar-only instrumentation immediately around the actual wrapper call.
// A timestamp bracket is not evidence of interrupting C++ or a sampled C++ PC.
final class NativeDocumentCallTrace: @unchecked Sendable {
  static let shared = NativeDocumentCallTrace()
  private let lock = NSLock()
  private var label = ""
  private var calls: [String: [String: UInt64]] = [:]
  private var target: ObjectIdentifier?
  private var writes: [String] = []
  func prepare(_ label: String) {
    lock.lock(); defer { lock.unlock() }
    self.label = label
  }
  func begin() -> String {
    lock.lock(); defer { lock.unlock() }
    calls[label] = ["begin_ns": DispatchTime.now().uptimeNanoseconds]
    return label
  }
  func end(_ ticket: String) {
    lock.lock(); defer { lock.unlock() }
    calls[ticket, default: [:]]["end_ns"] = DispatchTime.now().uptimeNanoseconds
  }
  func writeback() {
    lock.lock(); defer { lock.unlock() }
    writes.append(label)
  }
  func arm(_ window: ObjectIdentifier) {
    lock.lock(); defer { lock.unlock() }
    target = window
  }
  func willClose(_ window: ObjectIdentifier) {
    lock.lock(); defer { lock.unlock() }
    guard window == target else { return }
    calls[label, default: [:]]["will_close_ns"] = DispatchTime.now().uptimeNanoseconds
  }
  func snapshot(_ ticket: String) -> [String: UInt64] {
    lock.lock(); defer { lock.unlock() }
    return calls[ticket] ?? [:]
  }
  func writeLabels() -> [String] {
    lock.lock(); defer { lock.unlock() }
    return writes
  }
}

struct LifetimeDocumentDriverView: View {
  var body: some View { Color.clear.onAppear { WindowDocumentDriver.shared.start() } }
}

@MainActor final class WindowDocumentDriver {
  static let shared = WindowDocumentDriver()
  private enum Phase { case idle, first, anchorConversion, opening, importing, conversion, hold, active, closing, observing, zero }
  private var phase = Phase.idle
  private var timer: Timer?
  private var observer: NSObjectProtocol?
  private var began = 0.0
  private var since = 0.0
  private var anchor: ObjectIdentifier?
  private var target: ObjectIdentifier?
  private var baseline = ""
  private var cycle = 1
  private var five = false
  private var directory: URL!
  private let labels = ["1mib-a", "1mib-b", "10mib-a", "10mib-b", "active-10mib"]
  private var label: String { labels[cycle - 1] }
  private var mib: Int { cycle <= 2 ? 1 : 10 }
  private let anchorSource = "汉语 汉字 简体 转换 测试。\r\nEmoji 👩🏽‍💻 é \0 KEEP\r\n\r\n"
  private let anchorResult = "漢語 漢字 簡體 轉換 測試。\r\nEmoji 👩🏽‍💻 é \0 KEEP\r\n\r\n"

  func start() {
    guard phase == .idle else { return }
    phase = .first
    began = ProcessInfo.processInfo.systemUptime
    do {
      directory = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
        .appendingPathComponent(NativeWindowLifecycleAudit.bundleID)
        .appendingPathComponent("documents-\(ProcessInfo.processInfo.processIdentifier)", isDirectory: true)
      try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: false)
      // Fixed historical oracle; never generated by the converter under test.
      for size in [1, 10] {
        let count = size * 1024 * 1024 - 3
        let repeats = count / anchorSource.utf8.count
        let pad = String(repeating: "x", count: count % anchorSource.utf8.count)
        let source = Data([0xEF, 0xBB, 0xBF]) + Data((String(repeating: anchorSource, count: repeats) + pad).utf8)
        let expected = Data((String(repeating: anchorResult, count: repeats) + pad).utf8)
        try source.write(to: directory.appendingPathComponent("input-\(size)mib.txt"))
        try expected.write(to: directory.appendingPathComponent("expected-\(size)mib.txt"))
        record("documents_fixture_\(size)", details: ["input_bytes": source.count, "input_sha256": documentDigest(source),
          "expected_bytes": expected.count, "expected_sha256": documentDigest(expected)])
      }
    } catch { finish("fixture_generation:\(error)"); return }
    observer = NotificationCenter.default.addObserver(forName: NSWindow.willCloseNotification, object: nil, queue: nil) { note in
      guard let window = note.object as? NSWindow else { return }
      NativeDocumentCallTrace.shared.willClose(ObjectIdentifier(window))
    }
    began = ProcessInfo.processInfo.systemUptime
    record("documents_started")
    let timer = Timer(timeInterval: 0.02, repeats: true) { _ in
      Task { @MainActor in WindowDocumentDriver.shared.tick() }
    }
    self.timer = timer
    RunLoop.main.add(timer, forMode: .common)
  }

  private func tick() {
    let now = ProcessInfo.processInfo.systemUptime
    guard now - began < 420 else { finish("timeout"); return }
    let windows = NSApp.windows.filter { $0.isVisible && $0.canBecomeMain }
    if let anchor, !baseline.isEmpty, phase != .zero,
       NativeWindowLifecycleAudit.documentAnchorHash(anchor) != baseline {
      finish("anchor_changed"); return
    }
    switch phase {
    case .idle: break
    case .first:
      guard windows.count == 1, now - began >= 10,
            let model = NativeWindowLifecycleAudit.documentModel(ObjectIdentifier(windows[0])) else { return }
      anchor = ObjectIdentifier(windows[0])
      model.applyPreset(.traditional)
      model.replaceSource(anchorSource)
      NativeDocumentCallTrace.shared.prepare("anchor")
      model.translate()
      phase = .anchorConversion
    case .anchorConversion:
      guard let model = anchor.flatMap(NativeWindowLifecycleAudit.documentModel), !model.isLoading else { return }
      guard model.error == nil, model.resultText == anchorResult,
            model.exportSnapshot?.text == anchorResult else { finish("anchor_conversion"); return }
      baseline = NativeWindowLifecycleAudit.documentAnchorHash(anchor!)!
      record("documents_anchor_ready")
      openNext()
    case .opening:
      guard windows.count == 2,
            let window = windows.first(where: { ObjectIdentifier($0) != anchor }),
            let model = NativeWindowLifecycleAudit.documentModel(ObjectIdentifier(window)) else { return }
      target = ObjectIdentifier(window)
      model.applyPreset(.traditional)
      model.importFile(directory.appendingPathComponent("input-\(mib)mib.txt"))
      record("document_\(label)_import_started")
      phase = .importing
    case .importing:
      guard let model = target.flatMap(NativeWindowLifecycleAudit.documentModel), !model.isImporting else { return }
      do {
        let original = try Data(contentsOf: directory.appendingPathComponent("input-\(mib)mib.txt"))
        guard model.error == nil, Data(model.inputText.utf8) == original.dropFirst(3),
              model.resultText.isEmpty, model.exportSnapshot == nil,
              model.sourceFilename == "input-\(mib)mib.txt" else { finish("import_content"); return }
      } catch { finish("import_check:\(error)"); return }
      record("document_\(label)_imported")
      NativeDocumentCallTrace.shared.prepare(label)
      model.translate()
      record("document_\(label)_conversion_started")
      phase = cycle == 5 ? .active : .conversion
    case .conversion:
      guard let model = target.flatMap(NativeWindowLifecycleAudit.documentModel), !model.isLoading else { return }
      do {
        let expected = try Data(contentsOf: directory.appendingPathComponent("expected-\(mib)mib.txt"))
        guard model.error == nil, let snapshot = model.exportSnapshot,
              snapshot.filename == "input-\(mib)mib-converted.txt",
              Data(model.resultText.utf8) == expected, Data(snapshot.text.utf8) == expected else {
          finish("conversion_content"); return
        }
        // The preparer extracts the unchanged shipping fileWrapper body into
        // this diagnostic-only overload: WriteConfiguration has no public init.
        // System save-panel / security-scope acceptance remains separate.
        let document = ConvertedTextDocument(text: snapshot.text)
        let wrapper = try document.diagnosticFileWrapper()
        let output = directory.appendingPathComponent("actual-\(label).txt")
        try wrapper.write(to: output, options: .atomic, originalContentsURL: nil)
        let actual = try Data(contentsOf: output)
        guard actual == expected else { finish("export_content"); return }
        record("document_\(label)_exported", details: ["export_filename": snapshot.filename,
          "actual_bytes": actual.count, "actual_sha256": documentDigest(actual), "byte_equal": true,
          "nul_count": actual.filter { $0 == 0 }.count])
      } catch { finish("export:\(error)"); return }
      since = ProcessInfo.processInfo.systemUptime
      phase = .hold
    case .hold:
      guard now - since >= 10 else { return }
      record("document_\(label)_before_close")
      windows.first { ObjectIdentifier($0) == target }?.performClose(nil)
      phase = .closing
    case .active:
      let call = NativeDocumentCallTrace.shared.snapshot(label)
      guard let begin = call["begin_ns"] else { return }
      guard call["end_ns"] == nil else { finish("missed_active_call"); return }
      guard DispatchTime.now().uptimeNanoseconds - begin >= 5_000_000,
            let model = target.flatMap(NativeWindowLifecycleAudit.documentModel), model.isLoading,
            let window = windows.first(where: { ObjectIdentifier($0) == target }) else { return }
      record("document_\(label)_before_close")
      NativeDocumentCallTrace.shared.arm(ObjectIdentifier(window))
      window.performClose(nil)
      phase = .closing
    case .closing:
      guard windows.count == 1, ObjectIdentifier(windows[0]) == anchor else { return }
      record("document_\(label)_closed")
      since = ProcessInfo.processInfo.systemUptime
      five = false
      phase = .observing
    case .observing:
      guard windows.count == 1 else { finish("unexpected_window"); return }
      if now - since >= 5 && !five { five = true; record("document_\(label)_plus_5") }
      if now - since >= 20 {
        record("document_\(label)_plus_20")
        if cycle < 5 { cycle += 1; openNext() }
        else {
          windows[0].performClose(nil)
          phase = .zero
          since = 0
          five = false
        }
      }
    case .zero:
      guard windows.isEmpty else { return }
      if since == 0 { record("documents_final_closed"); since = ProcessInfo.processInfo.systemUptime }
      if now - since >= 5 && !five { five = true; record("documents_final_plus_5") }
      if now - since >= 20 { record("documents_final_plus_20"); finish(nil) }
    }
  }

  private func openNext() {
    guard openNativeWindow() else { finish("new_window_menu_unavailable"); return }
    target = nil
    phase = .opening
  }

  private func openNativeWindow() -> Bool {
    guard let main = NSApp.mainMenu else { return false }
    var candidates: [(NSMenu, NSMenuItem)] = []
    func visit(_ menu: NSMenu) {
      for item in menu.items {
        let modifiers = item.keyEquivalentModifierMask.intersection([.command, .shift, .option, .control])
        if item.keyEquivalent.lowercased() == "n", modifiers == .command, item.action != nil {
          candidates.append((menu, item))
        }
        if let child = item.submenu { visit(child) }
      }
    }
    visit(main)
    guard candidates.count == 1 else { return false }
    let (menu, item) = candidates[0]
    menu.update()
    guard item.isEnabled, let index = menu.items.firstIndex(where: { $0 === item }) else { return false }
    menu.performActionForItem(at: index)
    return true
  }

  private func record(_ event: String, details: [String: Any] = [:]) {
    NativeWindowLifecycleAudit.documentRecord(event, anchor: anchor, label: label, details: details)
  }
  private func finish(_ failure: String?) {
    timer?.invalidate(); timer = nil
    if let observer { NotificationCenter.default.removeObserver(observer) }
    observer = nil
    record(failure.map { "documents_failed:\($0)" } ?? "documents_finished")
    NSApp.terminate(nil)
  }
}

extension NativeWindowLifecycleAudit {
  static func documentModel(_ window: ObjectIdentifier) -> HomeViewModel? {
    shared.models.values.compactMap(\.model).first { $0.window.map(ObjectIdentifier.init) == window }
  }
  static func documentAnchorHash(_ window: ObjectIdentifier) -> String? {
    guard let model = documentModel(window) else { return nil }
    let state: [String: Any] = ["source": model.inputText, "result": model.resultText,
      "export_text": model.exportSnapshot?.text ?? "", "export_name": model.resultFilename,
      "converting": model.isLoading, "importing": model.isImporting,
      "target": String(describing: model.targetOptions), "variant": String(describing: model.variantOptions),
      "region": String(describing: model.regionOptions)]
    return documentDigest(try! JSONSerialization.data(withJSONObject: state, options: [.sortedKeys]))
  }
  static func documentRecord(_ event: String, anchor: ObjectIdentifier?, label: String, details: [String: Any]) {
    let sizes: [[String: Any]] = shared.models.values.compactMap { box in
      guard let model = box.model else { return nil }
      return ["number": box.number, "source_bytes": model.inputText.utf8.count,
        "result_bytes": model.resultText.utf8.count, "has_export": model.exportSnapshot != nil]
    }.sorted { ($0["number"] as! Int) < ($1["number"] as! Int) }
    var fields: [String: Any] = ["label": label, "content_sizes": sizes,
      "anchor_fingerprint": anchor.flatMap(documentAnchorHash) ?? "",
      "quota": appDefaults[\.testNumbersPerDay], "pending_reservations": TestNumbersPerDayManager.diagnosticPendingCount,
      "native_call": NativeDocumentCallTrace.shared.snapshot(label),
      "result_writebacks": NativeDocumentCallTrace.shared.writeLabels()]
    fields.merge(details) { _, new in new }
    shared.record(event, details: fields)
  }
}
